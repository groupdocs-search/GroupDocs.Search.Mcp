# ---------------------------------------------------------------- write / check
function Write-Lf([string]$Path, [string]$Content) {
    $lf = ($Content -replace "`r`n", "`n")
    if (-not $lf.EndsWith("`n")) { $lf += "`n" }
    [System.IO.File]::WriteAllText($Path, $lf, (New-Object System.Text.UTF8Encoding($false)))
}
function Read-Norm([string]$Path) {
    if (-not (Test-Path $Path)) { return $null }
    ([System.IO.File]::ReadAllText($Path) -replace "`r`n", "`n")
}

$drift = @()
if (-not (Test-Path $genDir)) { New-Item -ItemType Directory -Path $genDir | Out-Null }

foreach ($fname in $files.Keys) {
    $path = Join-Path $genDir $fname
    $new  = (($files[$fname]) -replace "`r`n", "`n")
    if (-not $new.EndsWith("`n")) { $new += "`n" }
    if ((Read-Norm $path) -ne $new) {
        $drift += "install/generated/$fname"
        if (-not $Check) { Write-Lf $path $files[$fname] }
    }
}

# README block injection (only the marker region is touched)
$readmePath = Join-Path $repoRoot 'README.md'
$readme = [System.IO.File]::ReadAllText($readmePath)
$pattern = '(?s)<!-- install-buttons:start.*?install-buttons:end -->'
if ($readme -notmatch $pattern) { throw "README.md is missing the <!-- install-buttons:start/end --> marker block" }
$newReadme = [regex]::Replace($readme, $pattern, ($readmeBlock -replace "`r`n", "`n"))
if ($newReadme -ne $readme) {
    $drift += 'README.md (install-buttons block)'
    if (-not $Check) { [System.IO.File]::WriteAllText($readmePath, $newReadme, (New-Object System.Text.UTF8Encoding($false))) }
}

if ($Check) {
    if ($drift.Count -gt 0) {
        Write-Host "DRIFT - regenerate with: pwsh install/generate-install-links.ps1"
        $drift | ForEach-Object { Write-Host "  out of date: $_" }
        exit 1
    }
    Write-Host "install/generated + README install block are up to date (version $version)."
} else {
    Write-Host "Generated $($files.Keys.Count) files (version $version); README block updated."
    if ($drift.Count -eq 0) { Write-Host "  (no changes - already up to date)" }
}
