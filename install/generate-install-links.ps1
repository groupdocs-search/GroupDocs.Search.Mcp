# Generates one-click install links + per-client mcp.json snippets from the ONE
# canonical config (install/config.json) so README buttons, deeplinks, and snippets
# can never drift from each other.
#
#   pwsh install/generate-install-links.ps1          # regenerate install/generated/ + README block
#   pwsh install/generate-install-links.ps1 -Check   # exit 1 if anything is out of date (CI drift guard)
#
# Supports two modes, selected by config.json's "command":
#   - dnx    : NuGet-first products (dnx <PackageId> --yes)
#   - docker : Docker-first products (docker run ... ghcr.io/...:latest) - used where the
#              packed tool exceeds NuGet.org's 250 MB limit, so there is NO dnx path.
#
# The package version is read from build/dependencies.props at generation time -
# config.json intentionally has no version field. Compatible with Windows
# PowerShell 5.1 and pwsh 7+; output is UTF-8 (no BOM) with LF endings so the
# same bytes are produced on every OS (see .gitattributes).
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$genDir   = Join-Path $PSScriptRoot 'generated'

# ---------------------------------------------------------------- inputs
$cfg = Get-Content (Join-Path $PSScriptRoot 'config.json') -Raw | ConvertFrom-Json

$propName  = ($cfg.packageId -replace '\.', '')   # GroupDocs.Search.Mcp -> GroupDocsSearchMcp
$depsText  = Get-Content (Join-Path $repoRoot 'build/dependencies.props') -Raw
$m = [regex]::Match($depsText, "<$propName>([^<]+)</$propName>")
if (-not $m.Success) { throw "Version property <$propName> not found in build/dependencies.props" }
$version = $m.Groups[1].Value.Trim()

$name     = $cfg.name
$pkg      = $cfg.packageId
$isDocker = ($cfg.command -eq 'docker')
$argsJson = '["' + ($cfg.args -join '", "') + '"]'

# EscapeDataString diverges between .NET Framework (PS 5.1, RFC 2396: leaves !'()*
# unescaped) and modern .NET (pwsh, RFC 3986: escapes them). Normalize so the
# generated bytes are identical on both - required for the CI drift guard.
function Escape-Uri([string]$s) {
    $e = [uri]::EscapeDataString($s)
    $e.Replace('(', '%28').Replace(')', '%29').Replace('!', '%21').Replace("'", '%27').Replace('*', '%2A')
}

# ---------------------------------------------------------------- JSON fragments
# Built as literal strings (NOT ConvertTo-Json) so output is byte-identical across
# PowerShell versions - required for the CI drift guard.
if ($isDocker) {
    $image = $cfg.args[-1]                       # e.g. ghcr.io/groupdocs-search/search-net-mcp:latest
    $imageBase = ($image -split ':')[0..(($image -split ':').Count - 2)] -join ':'

    $mcpServersSnippet = @"
{
  "mcpServers": {
    "$name": {
      "command": "docker",
      "args": ["run", "--rm", "-i", "-v", "/path/to/documents:/data", "-e", "GROUPDOCS_MCP_STORAGE_PATH=/data", "-e", "GROUPDOCS_MCP_OUTPUT_PATH=/data", "-e", "GROUPDOCS_LICENSE_PATH=", "$image"]
    }
  }
}
"@

    $vscodeSnippet = @"
{
  "inputs": [
    {
      "type": "promptString",
      "id": "storage_path",
      "description": "Base folder for input and output files.",
      "password": false
    }
  ],
  "servers": {
    "$name": {
      "command": "docker",
      "args": ["run", "--rm", "-i", "-v", "`${input:storage_path}:/data", "-e", "GROUPDOCS_MCP_STORAGE_PATH=/data", "-e", "GROUPDOCS_MCP_OUTPUT_PATH=/data", "-e", "GROUPDOCS_LICENSE_PATH=", "$image"]
    }
  }
}
"@

    $vscodeConfig = '{"command":"docker","args":["run","--rm","-i","-v","/path/to/documents:/data","-e","GROUPDOCS_MCP_STORAGE_PATH=/data","-e","GROUPDOCS_MCP_OUTPUT_PATH=/data","-e","GROUPDOCS_LICENSE_PATH=","' + $image + '"]}'
    $cursorConfig = $vscodeConfig

    $pinNote = "Pin a version by replacing ``:latest`` with ``:$version`` in the image tag."
    $cliLine = "docker run --rm -i -v /path/to/documents:/data $image"
    $cliLicensed = "docker run --rm -i -v /path/to/documents:/data -v /path/to/license-folder:/license -e GROUPDOCS_LICENSE_PATH=/license/GroupDocs.Total.lic $image"
} else {
    # All supported env vars are pre-filled so users see the full configuration surface:
    # output defaults to the same folder as storage; an EMPTY license path is safe -
    # LicenseManager treats null/empty identically (evaluation mode, no error).
    $envBlock = @"
        "GROUPDOCS_MCP_STORAGE_PATH": "/path/to/documents",
        "GROUPDOCS_MCP_OUTPUT_PATH": "/path/to/documents",
        "GROUPDOCS_LICENSE_PATH": ""
"@

    $mcpServersSnippet = @"
{
  "mcpServers": {
    "$name": {
      "type": "stdio",
      "command": "$($cfg.command)",
      "args": $argsJson,
      "env": {
$envBlock
      }
    }
  }
}
"@

    $vscodeSnippet = @"
{
  "inputs": [
    {
      "type": "promptString",
      "id": "storage_path",
      "description": "Base folder for input and output files.",
      "password": false
    },
    {
      "type": "promptString",
      "id": "license_path",
      "description": "Path to GroupDocs license file (optional - evaluation mode if empty).",
      "password": false
    }
  ],
  "servers": {
    "$name": {
      "type": "stdio",
      "command": "$($cfg.command)",
      "args": $argsJson,
      "env": {
        "GROUPDOCS_MCP_STORAGE_PATH": "`${input:storage_path}",
        "GROUPDOCS_MCP_OUTPUT_PATH": "`${input:storage_path}",
        "GROUPDOCS_LICENSE_PATH": "`${input:license_path}"
      }
    }
  }
}
"@

    $vscodeConfig = '{"command":"' + $cfg.command + '","args":' + ($argsJson -replace '", "', '","') + ',"env":{"GROUPDOCS_MCP_STORAGE_PATH":"/path/to/documents","GROUPDOCS_MCP_OUTPUT_PATH":"/path/to/documents","GROUPDOCS_LICENSE_PATH":""}}'
    $cursorConfig = $vscodeConfig

    $pinNote = "Pin a version by replacing ``$pkg`` with ``$pkg@$version``."
    $cliLine = "$($cfg.command) $($cfg.args -join ' ')"
    $cliLicensed = "the same command with -e GROUPDOCS_MCP_STORAGE_PATH=/path/to/documents -e GROUPDOCS_LICENSE_PATH=/path/to/GroupDocs.Total.lic"
}

# ---------------------------------------------------------------- one-click URLs
# vscode.dev's WAF (Azure Front Door) blocks any request carrying an `inputs=` query
# parameter (403 'The request is blocked'), so the one-click deeplink config is
# prompt-less: command+args only. The note under the buttons tells users how to set
# their storage folder after install. Verified empirically 2026-07-25 (inputs= -> 403,
# config-only -> 302 on both hosts; env values inside config= are fine, only inputs= trips it).
$encName   = Escape-Uri $name
$encConfig = Escape-Uri $vscodeConfig
$vscodeUrl         = "https://vscode.dev/redirect/mcp/install?name=$encName&config=$encConfig"
$vscodeInsidersUrl = "https://insiders.vscode.dev/redirect/mcp/install?name=$encName&config=$encConfig&quality=insiders"

# Cursor: TODO(verify) - format per cursor.com deeplink docs (name + base64 config);
# re-check against current Cursor docs before each rollout wave, it has changed before.
$cursorB64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($cursorConfig))
$cursorUrl = "https://cursor.com/en/install-mcp?name=$encName&config=$(Escape-Uri $cursorB64)"

$badgeVsCode   = "[![Install in VS Code](https://img.shields.io/badge/VS_Code-Install-0098FF)](${vscodeUrl})"
$badgeInsiders = "[![Install in VS Code Insiders](https://img.shields.io/badge/VS_Code_Insiders-Install-24bfa5)](${vscodeInsidersUrl})"
$badgeCursor   = "[![Add to Cursor](https://img.shields.io/badge/Cursor-Add_MCP-111111)](${cursorUrl})"
# Codex and Windsurf have no URL install scheme (Codex = CLI command, Windsurf = config
# file only), so their panel badges link to the generated setup guides instead.
$badgeCodex    = "[![Codex CLI setup](https://img.shields.io/badge/Codex_CLI-Setup-e5541b)](install/generated/codex.md)"
$badgeWindsurf = "[![Windsurf setup](https://img.shields.io/badge/Windsurf-Setup-0e8a7d)](install/generated/windsurf.md)"

# ---------------------------------------------------------------- generated files
$files = [ordered]@{}

$files['claude-desktop.json'] = $mcpServersSnippet
$files['windsurf.json']       = $mcpServersSnippet
$files['cline.json']          = $mcpServersSnippet
$files['vscode-mcp.json']     = $vscodeSnippet
$files['vs2022-mcp.json']     = $vscodeSnippet   # VS 2022 17.14+ reads the same shape from .mcp.json in the solution root

$files['claude-code.md'] = @"
